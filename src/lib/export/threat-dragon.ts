import { db } from "@/db";

export function exportAnalysisToThreatDragon(analysisId: string): any {
  const analysis = db.analyses.findFirst(analysisId);
  if (!analysis) throw new Error("Analysis not found");

  const modelRecord = db.systemModels.findFirst(analysisId);
  const systemModel = modelRecord
    ? {
        entities: JSON.parse(modelRecord.entities || "[]"),
        processes: JSON.parse(modelRecord.processes || "[]"),
        dataStores: JSON.parse(modelRecord.dataStores || "[]"),
        dataFlows: JSON.parse(modelRecord.dataFlows || "[]"),
        trustBoundaries: JSON.parse(modelRecord.trustBoundaries || "[]"),
      }
    : null;

  const threats = db.strideThreats.findMany(analysisId);
  const logicScenarios = db.businessLogicScenarios.findMany(analysisId);

  // Map elements to Threat Dragon diagram cells
  const cells: any[] = [];
  let posX = 100;
  let posY = 100;

  // External Entities
  (systemModel?.entities || []).forEach((e: any, idx: number) => {
    cells.push({
      type: "tm.Actor",
      size: { width: 140, height: 70 },
      position: { x: posX + (idx % 3) * 220, y: posY + Math.floor(idx / 3) * 120 },
      id: e.id,
      attrs: {
        text: { text: e.name },
      },
      data: { type: "tm.Actor", description: e.description },
    });
  });

  // Processes
  (systemModel?.processes || []).forEach((p: any, idx: number) => {
    cells.push({
      type: "tm.Process",
      size: { width: 150, height: 80 },
      position: { x: posX + 300 + (idx % 3) * 220, y: posY + Math.floor(idx / 3) * 120 },
      id: p.id,
      attrs: {
        text: { text: p.name },
      },
      data: { type: "tm.Process", description: p.description, tech: p.tech },
    });
  });

  // Data Stores
  (systemModel?.dataStores || []).forEach((s: any, idx: number) => {
    cells.push({
      type: "tm.Store",
      size: { width: 150, height: 75 },
      position: { x: posX + 600 + (idx % 2) * 220, y: posY + Math.floor(idx / 2) * 120 },
      id: s.id,
      attrs: {
        text: { text: s.name },
      },
      data: { type: "tm.Store", tech: s.tech },
    });
  });

  // Data Flows
  (systemModel?.dataFlows || []).forEach((f: any) => {
    cells.push({
      type: "tm.Flow",
      source: { id: f.sourceId },
      target: { id: f.targetId },
      id: f.id,
      labels: [{ position: 0.5, attrs: { text: { text: f.dataTransferred || f.protocol || "flow" } } }],
      data: { protocol: f.protocol },
    });
  });

  // Map threats to Threat Dragon Threat model
  const threatDragonThreats = [
    ...threats.map((t) => ({
      id: t.id.includes("_") ? t.id.split("_")[1] : t.id,
      title: t.title,
      type: t.strideCategory,
      status: "Open",
      severity: t.impact >= 4 ? "High" : t.impact >= 3 ? "Medium" : "Low",
      description: t.attackNarrative,
      mitigation: JSON.parse(t.recommendedMitigations || "[]").join("; "),
      modelType: "STRIDE",
    })),
    ...logicScenarios.map((s, idx) => ({
      id: `BL-${String(idx + 1).padStart(3, "0")}`,
      title: s.title,
      type: s.abuseCategory,
      status: "Open",
      severity: s.impactScore >= 4 ? "High" : "Medium",
      description: `${s.businessImpact}\n\nPreconditions: ${JSON.parse(s.preconditions || "[]").join(", ")}`,
      mitigation: JSON.parse(s.mitigations || "[]").join("; "),
      modelType: "BusinessLogic",
    })),
  ];

  return {
    version: "2.0",
    summary: {
      title: analysis.title,
      owner: "Security Architecture Team",
      description: `Threat model generated by Abuse Case Workbench for ${analysis.title}`,
    },
    detail: {
      diagrams: [
        {
          id: `${analysisId.slice(0, 8)}_dfd`,
          title: "System Data Flow & Threat Matrix",
          diagramType: "STRIDE",
          cells,
        },
      ],
      threats: threatDragonThreats,
    },
  };
}
