import { db } from "@/db";

export function exportAnalysisToMarkdown(analysisId: string): string {
  const analysis = db.analyses.findFirst(analysisId);
  if (!analysis) throw new Error("Analysis not found");

  const modelRecord = db.systemModels.findFirst(analysisId);
  const systemModel = modelRecord
    ? {
        entities: JSON.parse(modelRecord.entities || "[]"),
        processes: JSON.parse(modelRecord.processes || "[]"),
        dataStores: JSON.parse(modelRecord.dataStores || "[]"),
        dataFlows: JSON.parse(modelRecord.dataFlows || "[]"),
        trustBoundaries: JSON.parse(modelRecord.trustBoundaries || "[]"),
        technologies: JSON.parse(modelRecord.technologies || "[]"),
      }
    : null;

  const threats = db.strideThreats.findMany(analysisId);
  const logicScenarios = db.businessLogicScenarios.findMany(analysisId);
  const cves = db.cveFindings.findMany(analysisId);
  const riskRegister = db.riskRegister.findMany(analysisId);

  const criticalCount = riskRegister.filter((r) => (r.userOverrideSeverity || r.riskSeverity) === "CRITICAL").length;
  const highCount = riskRegister.filter((r) => (r.userOverrideSeverity || r.riskSeverity) === "HIGH").length;
  const mediumCount = riskRegister.filter((r) => (r.userOverrideSeverity || r.riskSeverity) === "MEDIUM").length;
  const lowCount = riskRegister.filter((r) => (r.userOverrideSeverity || r.riskSeverity) === "LOW").length;

  return `# Threat Modeling & Security Architecture Report: ${analysis.title}

**Generated by:** Abuse Case Workbench (Principal AppSec Engine)  
**Date:** ${new Date().toISOString().split("T")[0]}  
**Model Snapshot:** ${analysis.modelSnapshot}  
**Total Identified Findings:** ${riskRegister.length}  

---

## 1. Executive Summary & Risk Posture

| Severity Rating | Count | Status Distribution |
| :--- | :--- | :--- |
| **CRITICAL** | ${criticalCount} | Action required prior to production deployment |
| **HIGH** | ${highCount} | Planned for immediate sprint mitigation |
| **MEDIUM** | ${mediumCount} | Scheduled in backlog hardening |
| **LOW / INFO** | ${lowCount} | Accepted / Monitored baseline |

---

## 2. System Model & Architectural Topology

- **External Entities (${systemModel?.entities?.length || 0}):** ${systemModel?.entities?.map((e: any) => `\`${e.name}\` (${e.type})`).join(", ") || "None"}
- **Processes (${systemModel?.processes?.length || 0}):** ${systemModel?.processes?.map((p: any) => `\`${p.name}\`${p.tech ? ` [${p.tech}]` : ""}`).join(", ") || "None"}
- **Data Stores (${systemModel?.dataStores?.length || 0}):** ${systemModel?.dataStores?.map((s: any) => `\`${s.name}\`${s.tech ? ` [${s.tech}]` : ""}`).join(", ") || "None"}
- **Trust Boundaries (${systemModel?.trustBoundaries?.length || 0}):** ${systemModel?.trustBoundaries?.map((b: any) => `\`${b.name}\``).join(", ") || "None"}

---

## 3. Unified Risk Register

| ID | Type | Title | Component / Asset | Score | Severity | Status |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
${riskRegister
  .map(
    (r) =>
      `| \`${r.findingRefId}\` | ${r.findingType} | ${r.title.replace(/\|/g, "-")} | \`${r.affectedAssetOrComponent}\` | **${(r.userOverrideScore ?? r.calculatedRiskScore).toFixed(1)}** | **${r.userOverrideSeverity ?? r.riskSeverity}** | \`${r.userStatus}\` |`
  )
  .join("\n")}

---

## 4. Stage 3: Business Logic Abuse Scenarios

${logicScenarios.length === 0 ? "_No business logic scenarios generated._" : logicScenarios.map((s, idx) => {
  const abuseSeq = JSON.parse(s.abuseSequence || "[]");
  const mitigations = JSON.parse(s.mitigations || "[]");
  const signals = JSON.parse(s.detectionSignals || "[]");
  return `### BL-${String(idx + 1).padStart(3, "0")}: ${s.title}
- **Workflow:** \`${s.workflow}\`
- **Category:** ${s.abuseCategory}
- **Business Impact:** ${s.businessImpact}
- **Impact:** ${s.impactScore}/5 | **Likelihood:** ${s.likelihoodScore}/5

#### State Machine Abuse Sequence:
${abuseSeq.map((step: string, i: number) => `${i + 1}. ${step}`).join("\n")}

#### Pentest Reproduction Instructions:
\`\`\`
${s.pentestTestCase}
\`\`\`

#### SIEM Detection Signals:
${signals.map((sig: string) => `- ${sig}`).join("\n")}

#### Mitigations:
${mitigations.map((m: string) => `- ${m}`).join("\n")}
`;
}).join("\n---\n\n")}

---

## 5. Stage 2: STRIDE Threats Breakdown

${threats.length === 0 ? "_No STRIDE threats recorded._" : threats.map((t) => {
  const cwes = JSON.parse(t.cweIds || "[]");
  const mitigations = JSON.parse(t.recommendedMitigations || "[]");
  return `### [${t.strideCategory}] ${t.title} (\`${t.id.includes("_") ? t.id.split("_")[1] : t.id}\`)
- **Target Element:** \`${t.affectedElementId}\` (${t.affectedElementType})
- **Attack Narrative:** ${t.attackNarrative}
- **Preconditions:** ${t.attackerPrecondition}
- **Verified References:** ${cwes.length > 0 ? cwes.join(", ") : "None"}
- **Recommended Mitigations:**
${mitigations.map((m: string) => `  - ${m}`).join("\n")}
`;
}).join("\n")}

---

## 6. Stage 4: Grounded CVE Vulnerabilities

${cves.length === 0 ? "_No external CVEs correlated._" : cves.map((c) => `
- **\`${c.cveId}\`** on **${c.componentName}** (CVSS: ${c.cvssScore ?? "N/A"} | EPSS: ${c.epssScore ? `${(c.epssScore * 100).toFixed(1)}%` : "N/A"}${c.isKev ? " | **CISA KEV**" : ""})
  - *Contextual Relevance:* ${c.contextualRelevance}
  - *Source:* [${c.primarySource}](${c.sourceUrl})
`).join("\n")}
`;
}
